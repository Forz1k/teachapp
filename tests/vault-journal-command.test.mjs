import {lessonHistoryKey} from '../js/grade-history.js';
import {vaultRouterLab,routedDataAccessLab} from '../tools/prototypes/vault-router-lab.mjs';
const password='synthetic-journal-command-password';
const locks=()=>{const tails=new Map();return {request(name,opts,fn){const p=(tails.get(name)||Promise.resolve()).then(fn);tails.set(name,p.catch(()=>{}));return p;}};};
test('Production journal command executes unchanged through encrypted backend; preserves grade history and rejects stale history, lesson and special marks',async t=>{
 await D.clearAll();t.after(()=>D.clearAll());
 const data=Object.fromEntries(Object.keys(D.SCHEMA).map(n=>[n,[]]));
 data.classes=[{id:'c',name:'7А',gradeLevel:7}];data.students=[{id:'p',classId:'c',fullName:'Synthetic P',number:1,normGroup:'girls'}];
 data.lessons=[{id:'l',classId:'c',date:'2025-09-01',slot:1,time:'09:00'}];
 data.marks=[{id:'m',studentId:'p',lessonId:'l',value:'4',flag:null,source:'manual',weight:2}];
 await D.replaceAll(data);await S.load();
 const router=vaultRouterLab('shared-journal-command',{locks:locks()});await router.initialize();const src=routedDataAccessLab(router,{expectedGeneration:1});await src.replaceAll(data);src.close();
 await router.stage({password});await router.activate({password});const a=routedDataAccessLab(router,{expectedGeneration:2,password});t.after(()=>a.close());
 const opt={replace:true,requireLessonSnapshot:true};
 const plan=async(access,value)=>{const m=await access.get('marks','m'),l=await access.get('lessons','l'),h=await access.get('workRecords',lessonHistoryKey('p','l'));return {studentId:'p',studentName:'Synthetic P',lessonId:'l',date:l.date,slot:l.slot,time:l.time,value,expectedMark:J.journalMarkSnapshot(m),expectedLesson:J.journalLessonSnapshot(l),expectedHistoryId:h?.events.at(-1)?.id??null};};
 const initial=await plan(a,'5');
 assert.equal(await S.applyJournalPaste('c',[initial],true,opt),1);
 assert.equal((await J.writeJournalPaste(a,'c',[initial],true,opt))[0].value,'5');
 assert.deepEqual(await a.get('marks','m'),await D.get('marks','m'));assert.equal(S.state.marks[0].value,'5');
 const history=await a.get('workRecords',lessonHistoryKey('p','l'));assert.deepEqual(history.events.map(e=>[e.before,e.after,e.source]),(await D.get('workRecords',history.id)).events.map(e=>[e.before,e.after,e.source]));
 const stale=await plan(a,'3');await J.writeJournalPaste(a,'c',[await plan(a,'4')],true,opt);await J.writeJournalPaste(a,'c',[await plan(a,'5')],true,opt);
 await assert.rejects(J.writeJournalPaste(a,'c',[stale],true,opt),/История оценки изменилась/);
 assert.equal((await a.get('marks','m')).value,'5');
 const old=await plan(a,'2');await a.put('lessons',{...data.lessons[0],held:true});
 await assert.rejects(J.writeJournalPaste(a,'c',[old],true,opt),/состояние урока изменились/);
 await a.put('marks',{...await a.get('marks','m'),value:null,flag:'Н'});
 await assert.rejects(J.writeJournalPaste(a,'c',[await plan(a,'2')],true,opt),/особым/);
 assert.equal((await a.get('marks','m')).flag,'Н');assert.equal((await a.get('workRecords',history.id)).events.length,3);
 assert.equal((await D.get('marks','m')).value,'5');assert.equal((await D.get('workRecords',history.id)).events.length,1);
});
